"""The Assurance Map — generated from the tests, never written by hand.

Doc 25's method, applied to the whole suite: every test is tagged with the
statements it discharges, and **the unmapped remainder is the gap**, in both
directions:

- a test that names **no** statement verifies a feature no specification
  requires — exactly what a regeneration from the specs would lose;
- a statement **no** test names is a specification nothing verifies.

The unit is the test *function*. A parametrised function is one feature with
many cases, and counting its cases would let one well-parametrised test make an
untagged suite look tagged.

`@pytest.mark.tooling` marks a test of the instruments rather than of the agent —
the golden-set generator, the conformance report itself. Those are listed, and
kept out of the untagged remainder, because they are not features a regenerated
agent would need.
"""

from __future__ import annotations

import json
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

from evals.statements import FAMILIES, Vocabulary


@dataclass(frozen=True)
class Outcome:
    nodeid: str
    ids: tuple[str, ...]
    passed: bool
    tooling: bool

    @property
    def function(self) -> str:
        return self.nodeid.split("[", 1)[0]


def build(outcomes: list[Outcome], vocab: Vocabulary) -> dict:
    functions: dict[str, dict] = {}
    for o in outcomes:
        f = functions.setdefault(o.function, {"ids": set(), "passed": True, "tooling": False})
        f["ids"] |= set(o.ids)
        f["passed"] &= o.passed
        f["tooling"] |= o.tooling

    by_statement: dict[str, dict[str, list[str]]] = defaultdict(
        lambda: {"passed": [], "failed": []}
    )
    for name, f in functions.items():
        for sid in f["ids"]:
            by_statement[sid]["passed" if f["passed"] else "failed"].append(name)

    untagged = sorted(n for n, f in functions.items() if not f["ids"] and not f["tooling"])
    tooling = sorted(n for n, f in functions.items() if f["tooling"])

    families = {}
    for fam in FAMILIES:
        owed = vocab.owed(fam)
        exercised = [s for s in owed if s.id in by_statement]
        failing = [s.id for s in owed if by_statement.get(s.id, {}).get("failed")]
        families[fam] = {
            "owed": len(owed),
            "exercised": len(exercised),
            "failing": failing,
            "not_exercised": [
                {"id": s.id, "title": s.title} for s in owed if s.id not in by_statement
            ],
        }

    return {
        "generated_from": "the test suite's discharges markers — do not edit",
        "functions": len(functions),
        "tagged": sum(1 for f in functions.values() if f["ids"]),
        "tooling": tooling,
        "untagged": untagged,
        "families": families,
        "unchecked_families": vocab.unchecked,
        "by_statement": {k: v for k, v in sorted(by_statement.items())},
    }


def summary(m: dict) -> str:
    parts = [
        f"assurance map: {m['tagged']}/{m['functions']} test functions tagged, "
        f"{len(m['untagged'])} untagged, {len(m['tooling'])} tooling"
    ]
    for fam, f in m["families"].items():
        parts.append(f"{fam} {f['exercised']}/{f['owed']}")
    return " · ".join(parts)


def render(m: dict) -> str:
    lines = [
        "# Assurance Map",
        "",
        "*Generated by `pytest --assurance-map` from the suite's `discharges` markers.",
        "Never edit by hand — regenerate.*",
        "",
        f"**{m['tagged']} of {m['functions']}** test functions name a statement they discharge; "
        f"**{len(m['untagged'])}** name none; {len(m['tooling'])} test the instruments.",
        "",
        "| Spec | Owed | Exercised | Failing | Not exercised |",
        "|---|---|---|---|---|",
    ]
    for fam, f in m["families"].items():
        lines.append(
            f"| {fam} | {f['owed']} | {f['exercised']} | {len(f['failing'])} "
            f"| {len(f['not_exercised'])} |"
        )
    if m["unchecked_families"]:
        lines += ["", f"*Not validated — source not found:* {', '.join(m['unchecked_families'])}"]

    lines += [
        "",
        "## Tests that name no statement",
        "",
        "A feature no specification requires. Each one is either a missing statement —",
        "which spec, the routing rule decides — or a test that should be tagged.",
        "",
    ]
    by_file: dict[str, list[str]] = defaultdict(list)
    for name in m["untagged"]:
        path, _, fn = name.partition("::")
        by_file[path].append(fn)
    for path, fns in sorted(by_file.items()):
        lines.append(f"- `{path}` — {len(fns)}: " + ", ".join(f"`{f}`" for f in fns))

    lines += ["", "## Statements no test names", ""]
    for fam, f in m["families"].items():
        if not f["not_exercised"]:
            continue
        lines.append(f"### {fam} — {len(f['not_exercised'])}")
        lines.append("")
        for s in f["not_exercised"]:
            lines.append(f"- `{s['id']}` {s['title']}")
        lines.append("")
    return "\n".join(lines) + "\n"


def write(m: dict, directory: Path) -> None:
    (directory / "assurance-map.json").write_text(json.dumps(m, indent=2) + "\n")
    (directory / "ASSURANCE-MAP.md").write_text(render(m))


__all__ = ["Outcome", "build", "render", "summary", "write"]
