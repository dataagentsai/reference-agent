"""Which of this agent's statements a whole conversation has ever exercised.

The Assurance Map answers *is there a test*. This answers a harder question:
**has this statement ever been exercised by a customer talking to the agent
against a world that can refuse?** A unit test and a scenario are different
evidence — the first says a function behaves, the second says the behaviour
survives routing, assembly, a model, a tool boundary and a reply screen.

The gap between the two numbers is the honest measure of how much of this
agent's behaviour is asserted rather than demonstrated, and it is large today.
It is also the work list: the statements below are what G0.8 has left to write.
"""

from __future__ import annotations

from pathlib import Path

from agenttwin import load_scenario

from evals import statements

ROOT = Path(__file__).resolve().parents[1]
SCENARIOS = ROOT / "scenarios"


def reached(directory: Path = SCENARIOS) -> dict[str, list[str]]:
    """Statement id → the scenarios that reach it."""
    out: dict[str, list[str]] = {}
    for path in sorted(directory.glob("*.yaml")):
        scenario = load_scenario(path)
        for statement in scenario.discharges:
            out.setdefault(statement, []).append(path.stem)
    return out


def coverage(directory: Path = SCENARIOS) -> dict:
    owed = {s.id: s.title for s in statements.load().owed("AOAS")}
    hit = reached(directory)
    return {
        "owed": owed,
        "reached": {k: v for k, v in sorted(hit.items()) if k in owed},
        "unreached": sorted(set(owed) - set(hit)),
        "elsewhere": sorted(set(hit) - set(owed)),
    }


def render(report: dict) -> str:
    owed, hit, missing = report["owed"], report["reached"], report["unreached"]
    lines = [
        "# Scenario coverage",
        "",
        "*Generated by `scripts/scenario_coverage.py`. Never edit by hand — regenerate.*",
        "",
        f"**{len(hit)} of {len(owed)}** statements this agent owes have been exercised by a",
        "whole conversation, against a world that can refuse. The rest are asserted by",
        "tests and never demonstrated end to end, which is weaker evidence and is the",
        "distinction this page exists to keep visible.",
        "",
        "## Reached",
        "",
    ]
    for statement, scenarios in hit.items():
        lines.append(f"- `{statement}` — {', '.join(scenarios)}")
    lines += ["", f"## Reached by no scenario — {len(missing)}", ""]
    lines += [f"- `{s}` {owed[s]}" for s in missing]
    if report["elsewhere"]:
        lines += [
            "",
            "## Named by a scenario and not owed here",
            "",
            "Statements from the catalogs rather than this agent's own specification.",
            "",
        ]
        lines += [f"- `{s}`" for s in report["elsewhere"]]
    return "\n".join(lines) + "\n"


__all__ = ["coverage", "reached", "render"]
